// paths.rs — куда класть alchemist.db и alchemist_settings.json.
//
// Исходная egui-версия использовала std::env::current_dir() (рабочую
// директорию процесса) — это работало, пока пользователь всегда запускал
// .exe двойным кликом из его собственной папки. Здесь используем директорию
// самого исполняемого файла (current_exe()) — она не зависит от того, откуда
// запущен процесс, и ведёт себя предсказуемо в большем числе случаев
// (например, если кто-то создаст ярлык на рабочем столе). Поведение
// "положить alchemist.db рядом с exe и получить портативное приложение"
// сохраняется в точности как раньше.

use std::path::PathBuf;

// Готовая база (178 компонентов, 61 свойство, все картинки) зашивается
// прямо в бинарник на этапе компиляции — так и `cargo build`, и
// `npm run tauri dev`, и релизная сборка одинаково разворачивают полную
// базу при первом запуске, независимо от того, куда именно cargo кладёт
// исполняемый файл (в dev-режиме это src-tauri/target/debug/, что не
// совпадает с папкой проекта, где лежит исходная alchemist.db). Как только
// файл рядом с exe создан — дальше это обычный портативный alchemist.db,
// который можно свободно редактировать/переносить, как и раньше.
const SEED_DB: &[u8] = include_bytes!("../alchemist.db");

fn app_dir() -> PathBuf {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.to_path_buf()))
        .unwrap_or_else(|| PathBuf::from("."))
}

pub fn database_path() -> PathBuf {
    app_dir().join("alchemist.db")
}

pub fn settings_path() -> PathBuf {
    app_dir().join("alchemist_settings.json")
}

/// Если рядом с exe ещё нет alchemist.db — разворачивает туда зашитую в
/// бинарник копию (со всеми данными и картинками) перед тем, как db.rs
/// откроет соединение. Если файл уже есть (обычный случай при повторном
/// запуске, либо пользователь сам положил свою базу) — ничего не делает,
/// правки пользователя никогда не перезаписываются.
pub fn ensure_seed_db() -> std::io::Result<()> {
    let path = database_path();
    if path.exists() {
        return Ok(());
    }
    std::fs::write(&path, SEED_DB)
}
